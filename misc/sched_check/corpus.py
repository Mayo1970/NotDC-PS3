#!/usr/bin/env python3
# Builds corpus.inc for sched_check from the code dumps of HW logs: [HOT] dumps (hot + cold words) and [prof] dumps
# (the first 2 KB). Usage: corpus.py out.inc log1 log2 ...
import re
import sys

HOT = re.compile(r'^\[HOT\] --- dump pc=([0-9A-F]+) host=([0-9A-F]+): .*-> hot (\d+) B .*cold (\d+) B')
PROF = re.compile(r'^\[prof\] --- block ([0-9A-F]+) host=([0-9A-F]+): .* hot (\d+) B, cold (\d+) B')
PPC = re.compile(r'^\[(HOT|prof)\] ppc \+([0-9A-F]+) (.*)$')

blocks = {}
words = set()
for path in sys.argv[2:]:
    cur = None
    with open(path, 'r', errors='replace') as f:
        for line in f:
            line = line.rstrip('\r\n')
            m = HOT.match(line) or PROF.match(line)
            if m:
                if cur and cur['w']:
                    key = tuple(cur['w'][:cur['hot'] // 4])
                    if key and key not in blocks:
                        blocks[key] = cur
                cur = {'hot': int(m.group(3)), 'cold': int(m.group(4)), 'w': [], 'src': path}
                continue
            m = PPC.match(line)
            if m and cur is not None:
                off = int(m.group(2), 16)
                if off != len(cur['w']) * 4:
                    cur = None
                    continue
                for tok in m.group(3).split():
                    if re.fullmatch(r'[0-9A-F]{8}', tok):
                        v = int(tok, 16)
                        cur['w'].append(v)
                        words.add(v)
                continue
            if cur is not None and not line.startswith('[HOT] sh4') and not line.startswith('[prof] sh4'):
                if cur['w']:
                    key = tuple(cur['w'][:cur['hot'] // 4])
                    if key and key not in blocks:
                        blocks[key] = cur
                cur = None
    if cur and cur['w']:
        key = tuple(cur['w'][:cur['hot'] // 4])
        if key and key not in blocks:
            blocks[key] = cur

MAX_WORDS, MAX_HOT, MAX_PROF = 8000, 260, 90


def shape(w):
    op = w >> 26
    if op in (19, 31, 59, 63):
        return (op, (w >> 1) & 0x3FF, w & 1)
    if op == 30:
        return (op, (w >> 2) & 7, w & 1)
    return (op, w & 1 if op in (20, 21, 23) else 0)


# Every shape once, then an even sample of the rest; blocks: the complete [HOT] dumps first.
ws_all = sorted(words)
seen = {}
for w in ws_all:
    seen.setdefault(shape(w), w)
rest = [w for w in ws_all if w not in set(seen.values())]
step = max(1, len(rest) // max(1, MAX_WORDS - len(seen)))
words = set(seen.values()) | set(rest[::step][:MAX_WORDS - len(seen)])
full =[(k, b) for k, b in blocks.items() if len(b['w']) * 4 >= b['hot'] + b['cold']]
part = [(k, b) for k, b in blocks.items() if len(b['w']) * 4 < b['hot'] + b['cold']]
full.sort(key=lambda kb: hash(kb[0]) & 0xFFFFFFFF)
part.sort(key=lambda kb: hash(kb[0]) & 0xFFFFFFFF)
blocks = dict(full[:MAX_HOT] + part[:MAX_PROF])

out = []
out.append('// Generated by corpus.py from HW log code dumps. Not part of the PS3 build.')
ws = sorted(words)
out.append('static const u32 k_words[%d] = {' % len(ws))
for i in range(0, len(ws), 8):
    out.append('\t' + ', '.join('0x%08X' % w for w in ws[i:i + 8]) + ',')
out.append('};')
flat = []
index = []
for key, b in blocks.items():
    w = b['w']
    hot = min(b['hot'] // 4, len(w))
    index.append((len(flat), hot, len(w)))
    flat.extend(w)
out.append('static const u32 k_blk_words[%d] = {' % len(flat))
for i in range(0, len(flat), 8):
    out.append('\t' + ', '.join('0x%08X' % w for w in flat[i:i + 8]) + ',')
out.append('};')
out.append('static const u32 k_blk_index[%d][3] = {' % len(index))
for i in range(0, len(index), 6):
    out.append('\t' + ' '.join('{ %d, %d, %d },' % t for t in index[i:i + 6]))
out.append('};')
with open(sys.argv[1], 'w', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('words %d blocks %d block words %d' % (len(ws), len(index), len(flat)))
