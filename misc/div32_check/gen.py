#!/usr/bin/env python3
# Plan 5.38 (host, docker): div32_words.s through the build image's ppu-as into div32_words.inc for div32_check.cpp.
import os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

# Through bash as build.sh does: MSYS would rewrite the container paths of a direct call.
cmd = ('MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/src" -w /src ps3dev-latest:latest '
       'sh -c "ppu-as -mcell -a64 -o /tmp/d.o misc/div32_check/div32_words.s && ppu-objdump -d /tmp/d.o"')
out = subprocess.run(['bash', '-c', cmd], cwd=ROOT, check=True, capture_output=True, text=True).stdout
words = []
for line in out.splitlines():
    m = re.match(r'^\s*[0-9a-f]+:\s+((?:[0-9a-f]{2} ){4})\s*(.*)$', line)
    if m:
        words.append((int(m.group(1).replace(' ', ''), 16), m.group(2).strip()))
assert len(words) == 88, len(words)
with open(os.path.join(HERE, 'div32_words.inc'), 'w', newline='\n') as f:
    f.write('// Generated by gen.py from div32_words.s (ppu-as of the build image).\n')
    f.write('static const u32 k_ref[] = {\n')
    for w, text in words:
        f.write('\t0x%08Xu,\t// %s\n' % (w, text))
    f.write('};\n')
print('%d words' % len(words))
