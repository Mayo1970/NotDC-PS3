#!/usr/bin/env python3
# Plan 5.18: assembles hot_cases.s and hot_count.s with the build image's ppu-as and writes hot_words.inc,
# so hot_check.cpp tests hot_classify on real encodings. Run on the host with docker; run.sh needs only g++.
import os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))

def words(name):
    # Through bash as build.sh does: MSYS would rewrite the container paths of a direct call.
    cmd = ('MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/src" -w /src ps3dev-latest:latest '
           'sh -c "ppu-as -mcell -a64 -o /tmp/h.o misc/hot_check/%s && ppu-objdump -d /tmp/h.o"' % name)
    out = subprocess.run(['bash', '-c', cmd], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    res = []
    for line in out.splitlines():
        m = re.match(r'^\s*[0-9a-f]+:\s+((?:[0-9a-f]{2} ){4})\s*(.*)$', line)
        if m:
            res.append((int(m.group(1).replace(' ', ''), 16), m.group(2).strip()))
    return res

def expected(name):
    res = []
    for line in open(os.path.join(HERE, name)):
        if line.startswith('\t'):
            res.append(line.split('#', 1)[1].strip() if '#' in line else '')
    return res

cases, exp = words('hot_cases.s'), expected('hot_cases.s')
assert len(cases) == len(exp), (len(cases), len(exp))
count = words('hot_count.s')
with open(os.path.join(HERE, 'hot_words.inc'), 'w', newline='\n') as f:
    f.write('// Generated by gen.py from hot_cases.s and hot_count.s (ppu-as of the build image).\n')
    f.write('static const Case k_cases[] = {\n')
    for (w, text), e in zip(cases, exp):
        f.write('\t{ 0x%08Xu, "%s", "%s" },\n' % (w, text.replace('"', ''), e))
    f.write('};\n')
    f.write('static const u32 k_count_ref[] = {\n')
    for w, text in count:
        f.write('\t0x%08Xu,\t// %s\n' % (w, text))
    f.write('};\n')
print('%d cases, %d count words' % (len(cases), len(count)))
