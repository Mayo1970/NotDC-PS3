#!/bin/bash
# NotDC 3a: the fog programs into ../ps3gl_shader_fog.h, as compile_bump.sh (cgc.exe gives assembly, cgcomp -a the
# binaries). fog_fp.fcg builds once per "name FOG ENV BUMP" line; the order is ps3gl.h's PS3GL_TENV_FOG* order.
set -e
cd "$(dirname "$0")"

CGC="${CGC:-/c/Program Files (x86)/NVIDIA Corporation/Cg/bin/cgc.exe}"
if [ ! -x "$CGC" ]; then
    echo "ERROR: cgc.exe not found; set CGC= to the Cg Toolkit 3.1 cgc.exe"
    exit 1
fi

# cgcomp: native when the toolchain is installed here, else the one in the ps3dev Docker image.
cgcomp() {
    if [ -x "${PS3DEV:-/nonexistent}/bin/cgcomp" ]; then
        "$PS3DEV/bin/cgcomp" "$@"
    else
        MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/w" -w /w ps3dev-latest:latest \
            /usr/local/ps3dev/bin/cgcomp "$@"
    fi
}

PROGRAMS="
fogt_coloronly     1 0 0
fogt_modulate      1 1 0
fogt_replace       1 2 0
fogt_decal         1 3 0
fogt_bump_replace  1 2 1
fogt_bump_modulate 1 1 1
fogt_bump_decal    1 3 1
fogv_modulate      2 1 0
fogv_replace       2 2 0
fogv_decal         2 3 0
fogb_coloronly     3 0 0
fogb_modulate      3 1 0
fogb_modulate_ta   3 4 0
fogb_decal         3 3 0
"

echo "  fog_vp.vcg -> fog_vp.vpo"
"$CGC" -q -profile vp40 -o fog_vp.vpo.asm fog_vp.vcg
cgcomp -a -v fog_vp.vpo.asm fog_vp.vpo > /dev/null
rm -f -- fog_vp.vpo.asm

echo "$PROGRAMS" | while read -r name fog env bump; do
    [ -n "$name" ] || continue
    echo "  fog_fp.fcg (FOG=$fog ENV=$env BUMP=$bump) -> fog_fp_$name.fpo"
    "$CGC" -q -profile fp40 -DFOG="$fog" -DENV="$env" -DBUMP="$bump" -o "fog_fp_$name.fpo.asm" fog_fp.fcg < /dev/null
    cgcomp -a -f "fog_fp_$name.fpo.asm" "fog_fp_$name.fpo" > /dev/null < /dev/null
    rm -f -- "fog_fp_$name.fpo.asm"
done

python3 - $(echo "$PROGRAMS" | awk 'NF { print $1 }') <<'PYEOF'
import sys
files = [("fog_vp.vpo", "shader_vp_fog_data")]
files += [("fog_fp_%s.fpo" % n, "shader_fp_%s_data" % n) for n in sys.argv[1:]]
lines = [
    "/* ps3gl_shader_fog.h -- the NotDC 3a fog programs, embedded. Generated by shaders/compile_fog.sh. */",
    "#ifndef PS3GL_SHADER_FOG_H",
    "#define PS3GL_SHADER_FOG_H",
    "",
]
for fname, var in files:
    data = open(fname, "rb").read()
    lines.append("static const unsigned char %s[] __attribute__((aligned(16))) = {" % var)
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const unsigned int %s_size = %d;" % (var, len(data)))
    lines.append("")
lines.append("#endif /* PS3GL_SHADER_FOG_H */")
open("../ps3gl_shader_fog.h", "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote ../ps3gl_shader_fog.h")
PYEOF
