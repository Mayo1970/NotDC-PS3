#!/bin/bash
# NotDC bundle 17: the offset colour, colour clamp and trilinear programs into ../ps3gl_shader_dc.h, as compile_fog.sh.
# dc_fp.fcg builds once per "name FOG ENV OFFS XT" line; ps3gl_shaders.c finds a program by the table at the end.
set -e
cd "$(dirname "$0")"

CGC="${CGC:-/c/Program Files (x86)/NVIDIA Corporation/Cg/bin/cgc.exe}"
if [ ! -x "$CGC" ]; then
    echo "ERROR: cgc.exe not found; set CGC= to the Cg Toolkit 3.1 cgc.exe"
    exit 1
fi

# cgcomp: native when the toolchain is installed here, else the one in the ps3dev Docker image.
cgcomp() {
    if [ -x "${PS3DEV:-/nonexistent}/bin/cgcomp" ]; then
        "$PS3DEV/bin/cgcomp" "$@"
    else
        MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/w" -w /w ps3dev-latest:latest \
            /usr/local/ps3dev/bin/cgcomp "$@"
    fi
}

# OFFS alone (the offset colour): the bump VP with no fog, the fog VP with fog. XT: the dc VP.
PROGRAMS="
offs_modulate            0 1 1 0
offs_replace             0 2 1 0
offs_decal               0 3 1 0
fogt_offs_modulate       1 1 1 0
fogt_offs_replace        1 2 1 0
fogt_offs_decal          1 3 1 0
fogv_offs_modulate       2 1 1 0
fogv_offs_replace        2 2 1 0
fogv_offs_decal          2 3 1 0
fogb_offs_modulate       3 1 1 0
fogb_offs_modulate_ta    3 4 1 0
fogb_offs_decal          3 3 1 0
xt_coloronly             0 0 0 1
xt_modulate              0 1 0 1
xt_replace               0 2 0 1
xt_decal                 0 3 0 1
xt_fogt_coloronly        1 0 0 1
xt_fogt_modulate         1 1 0 1
xt_fogt_replace          1 2 0 1
xt_fogt_decal            1 3 0 1
xt_fogv_modulate         2 1 0 1
xt_fogv_replace          2 2 0 1
xt_fogv_decal            2 3 0 1
xt_fogb_coloronly        3 0 0 1
xt_fogb_modulate         3 1 0 1
xt_fogb_modulate_ta      3 4 0 1
xt_fogb_decal            3 3 0 1
xt_offs_modulate         0 1 1 1
xt_offs_replace          0 2 1 1
xt_offs_decal            0 3 1 1
xt_fogt_offs_modulate    1 1 1 1
xt_fogt_offs_replace     1 2 1 1
xt_fogt_offs_decal       1 3 1 1
xt_fogv_offs_modulate    2 1 1 1
xt_fogv_offs_replace     2 2 1 1
xt_fogv_offs_decal       2 3 1 1
xt_fogb_offs_modulate    3 1 1 1
xt_fogb_offs_modulate_ta 3 4 1 1
xt_fogb_offs_decal       3 3 1 1
"

echo "  dc_vp.vcg -> dc_vp.vpo"
"$CGC" -q -profile vp40 -o dc_vp.vpo.asm dc_vp.vcg
cgcomp -a -v dc_vp.vpo.asm dc_vp.vpo > /dev/null
rm -f -- dc_vp.vpo.asm

# One container for every program: a container per file takes minutes.
echo "$PROGRAMS" | while read -r name fog env offs xt; do
    [ -n "$name" ] || continue
    echo "  dc_fp.fcg (FOG=$fog ENV=$env OFFS=$offs XT=$xt) -> dc_fp_$name.fpo"
    "$CGC" -q -profile fp40 -DFOG="$fog" -DENV="$env" -DOFFS="$offs" -DXT="$xt" -o "dc_fp_$name.fpo.asm" dc_fp.fcg < /dev/null
done
if [ -x "${PS3DEV:-/nonexistent}/bin/cgcomp" ]; then
    for a in dc_fp_*.fpo.asm; do "$PS3DEV/bin/cgcomp" -a -f "$a" "${a%.asm}" > /dev/null; done
else
    MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/w" -w /w ps3dev-latest:latest \
        sh -c 'for a in dc_fp_*.fpo.asm; do /usr/local/ps3dev/bin/cgcomp -a -f "$a" "${a%.asm}" > /dev/null || exit 1; done'
fi
rm -f -- dc_fp_*.fpo.asm

echo "$PROGRAMS" | awk 'NF { print $1, $2, $3, $4, $5 }' > dc_programs.txt
python3 - <<'PYEOF'
progs = [l.split() for l in open("dc_programs.txt") if l.strip()]
lines = [
    "/* ps3gl_shader_dc.h -- the NotDC bundle 17 programs (offset colour, colour clamp, trilinear weight), embedded.",
    " * Generated by shaders/compile_dc.sh. */",
    "#ifndef PS3GL_SHADER_DC_H",
    "#define PS3GL_SHADER_DC_H",
    "",
]
def emit(fname, var):
    data = open(fname, "rb").read()
    lines.append("static const unsigned char %s[] __attribute__((aligned(16))) = {" % var)
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const unsigned int %s_size = %d;" % (var, len(data)))
    lines.append("")
emit("dc_vp.vpo", "shader_vp_dc_data")
for name, fog, env, offs, xt in progs:
    emit("dc_fp_%s.fpo" % name, "shader_fp_%s_data" % name)
# fog: the ps3gl_dc_fog() mode (FOG 3 with ENV 4 is PS3GL_FOG_BASE_TA); env: the texenv key (ENV 4 is MODULATE).
lines.append("/* Each program's place: xt = with the clamp and the weight, offs = with the offset colour, the PS3GL_FOG_* mode")
lines.append(" * and the PS3GL_TENV_* texenv it draws. */")
lines.append("static const struct { const unsigned char *data; unsigned int size; unsigned char xt, offs, fog, env; }")
lines.append("shader_dc_fp[] = {")
for name, fog, env, offs, xt in progs:
    mode = 4 if (fog == "3" and env == "4") else int(fog)
    tenv = 1 if env == "4" else int(env)
    lines.append("  { shader_fp_%s_data, sizeof(shader_fp_%s_data), %s, %s, %d, %d }," % (name, name, xt, offs, mode, tenv))
lines.append("};")
lines.append("")
lines.append("#endif /* PS3GL_SHADER_DC_H */")
open("../ps3gl_shader_dc.h", "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote ../ps3gl_shader_dc.h (%d programs)" % len(progs))
PYEOF
rm -f -- dc_programs.txt
