#!/bin/bash
# NotDC 3j: the bump programs into ../ps3gl_shader_bump.h. cgc.exe (Cg 3.1) gives assembly, cgcomp -a the binaries.
# Only bump_* files: re-running compile_shaders.sh would rebuild q3_vp.vpo, whose committed binary is an older build.
set -e
cd "$(dirname "$0")"

CGC="${CGC:-/c/Program Files (x86)/NVIDIA Corporation/Cg/bin/cgc.exe}"
if [ ! -x "$CGC" ]; then
    echo "ERROR: cgc.exe not found; set CGC= to the Cg Toolkit 3.1 cgc.exe"
    exit 1
fi

# cgcomp: native when the toolchain is installed here, else the one in the ps3dev Docker image.
cgcomp() {
    if [ -x "${PS3DEV:-/nonexistent}/bin/cgcomp" ]; then
        "$PS3DEV/bin/cgcomp" "$@"
    else
        MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/w" -w /w ps3dev-latest:latest \
            /usr/local/ps3dev/bin/cgcomp "$@"
    fi
}

build() {
    local src="$1" profile="$2" flag="$3" out="$4"
    echo "  $src -> $out"
    "$CGC" -q -profile "$profile" -o "$out.asm" "$src"
    cgcomp -a "$flag" "$out.asm" "$out" > /dev/null
    rm -f -- "$out.asm"
}

build bump_vp.vcg vp40 -v bump_vp.vpo
for fp in bump_fp_replace bump_fp_modulate bump_fp_decal; do
    build "$fp.fcg" fp40 -f "$fp.fpo"
done

python3 - <<'PYEOF'
files = [
    ("bump_vp.vpo",          "shader_vp_bump_data"),
    ("bump_fp_replace.fpo",  "shader_fp_bump_replace_data"),
    ("bump_fp_modulate.fpo", "shader_fp_bump_modulate_data"),
    ("bump_fp_decal.fpo",    "shader_fp_bump_decal_data"),
]
lines = [
    "/* ps3gl_shader_bump.h -- the NotDC 3j bump programs, embedded. Generated by shaders/compile_bump.sh. */",
    "#ifndef PS3GL_SHADER_BUMP_H",
    "#define PS3GL_SHADER_BUMP_H",
    "",
]
for fname, var in files:
    data = open(fname, "rb").read()
    lines.append("static const unsigned char %s[] __attribute__((aligned(16))) = {" % var)
    for i in range(0, len(data), 12):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    lines.append("static const unsigned int %s_size = %d;" % (var, len(data)))
    lines.append("")
lines.append("#endif /* PS3GL_SHADER_BUMP_H */")
open("../ps3gl_shader_bump.h", "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote ../ps3gl_shader_bump.h")
PYEOF
